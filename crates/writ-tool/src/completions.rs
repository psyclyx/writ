//! `writ completions bash|zsh|fish`: completion scripts generated from
//! [`crate::specs`], each in its shell's own idiom.

use crate::args::{Opt, Spec, Value};
use crate::specs::{self, GLOBAL_OPTS};
use std::fmt::Write as _;

/// The script for `shell`, or `None` if writ doesn't know the shell.
pub fn script(shell: &str) -> Option<String> {
    match shell {
        "bash" => Some(bash()),
        "zsh" => Some(zsh()),
        "fish" => Some(fish()),
        _ => None,
    }
}

fn commands() -> Vec<&'static Spec> {
    specs::all().collect()
}

fn opt_names(o: &Opt) -> Vec<String> {
    o.short
        .map(|c| format!("-{c}"))
        .into_iter()
        .chain([format!("--{}", o.long)])
        .collect()
}

// ---------------------------------------------------------------------------
// bash

fn bash_action(v: Value) -> String {
    match v {
        Value::NewDir | Value::Identity | Value::Id => "_writ_dirs".to_owned(),
        Value::File | Value::OutFile | Value::Subject => "_writ_files".to_owned(),
        Value::Text => ":".to_owned(),
        Value::Choice(words) => format!("_writ_words '{}'", words.join(" ")),
    }
}

fn bash() -> String {
    let mut s = String::from(
        r#"# bash completion for writ(1)                              -*- shell-script -*-
# Generated by `writ completions bash`. Install it as
# ~/.local/share/bash-completion/completions/writ.

_writ_words() {
    mapfile -t COMPREPLY < <(compgen -W "$1" -- "$cur")
}

_writ_files() {
    if declare -F _filedir >/dev/null; then
        _filedir
    else
        compopt -o filenames 2>/dev/null
        mapfile -t COMPREPLY < <(compgen -f -- "$cur")
    fi
}

_writ_dirs() {
    if declare -F _filedir >/dev/null; then
        _filedir -d
    else
        compopt -o filenames 2>/dev/null
        mapfile -t COMPREPLY < <(compgen -d -- "$cur")
    fi
}

# Prints the 1-based position of the argument being completed, counting
# positional arguments after the command and skipping option values.
# $1: the command's options that take a value, space-separated.
_writ_position() {
    local i n=1 skip=false
    for ((i = cmd_at + 1; i < cword; i++)); do
        if $skip; then
            skip=false
            continue
        fi
        case ${words[i]} in
            --) ;;
            --*=*) ;;
            -?*) [[ " $1 " == *" ${words[i]} "* ]] && skip=true ;;
            *) ((n++)) ;;
        esac
    done
    echo "$n"
}

_writ() {
    local cur prev words cword split=false
    if declare -F _init_completion >/dev/null; then
        _init_completion -s || return
    else
        COMPREPLY=()
        words=("${COMP_WORDS[@]}")
        cword=$COMP_CWORD
        cur=${COMP_WORDS[COMP_CWORD]}
        prev=${COMP_WORDS[COMP_CWORD - 1]}
        # Without bash-completion, "--opt=value" arrives as three words.
        if [[ $cur == = ]]; then
            cur=
        elif [[ $prev == = ]]; then
            prev=${COMP_WORDS[COMP_CWORD - 2]}
        fi
    fi

    local i cmd= cmd_at=0
    for ((i = 1; i < cword; i++)); do
        case ${words[i]} in
            --color) ((i++)) ;;
            -*) ;;
            *)
                cmd=${words[i]}
                cmd_at=$i
                break
                ;;
        esac
    done

    if [[ -z $cmd ]]; then
        case $prev in
            --color)
                _writ_words 'auto always never'
                return
                ;;
        esac
        if [[ $cur == -* ]]; then
            _writ_words '--color --help --version'
        else
"#,
    );
    let names: Vec<&str> = commands().iter().map(|c| c.name).chain(["help"]).collect();
    let _ = writeln!(s, "            _writ_words '{}'", names.join(" "));
    s.push_str("        fi\n        return\n    fi\n\n    case $cmd in\n");
    for spec in commands() {
        let _ = writeln!(s, "        {})", spec.name);
        let valued: Vec<&Opt> = spec.opts.iter().filter(|o| o.value.is_some()).collect();
        if !valued.is_empty() {
            s.push_str("            case $prev in\n");
            for o in &valued {
                let (_, v) = o.value.unwrap_or(("", Value::Text));
                let _ = writeln!(
                    s,
                    "                {})\n                    {}\n                    return\n                    ;;",
                    opt_names(o).join("|"),
                    bash_action(v)
                );
            }
            s.push_str("            esac\n");
        }
        let mut all: Vec<String> = spec.opts.iter().flat_map(opt_names).collect();
        all.extend(["-h".to_owned(), "--help".to_owned()]);
        let _ = writeln!(
            s,
            "            if [[ $cur == -* ]]; then\n                _writ_words '{}'\n                return\n            fi",
            all.join(" ")
        );
        if !spec.args.is_empty() {
            let valued_names: Vec<String> = valued.iter().flat_map(|o| opt_names(o)).collect();
            let _ = writeln!(
                s,
                "            case $(_writ_position '{}') in",
                valued_names.join(" ")
            );
            for (i, a) in spec.args.iter().enumerate() {
                let pattern = if a.many {
                    "*".to_owned()
                } else {
                    (i + 1).to_string()
                };
                let _ = writeln!(s, "                {pattern}) {} ;;", bash_action(a.value));
            }
            s.push_str("            esac\n");
        }
        s.push_str("            ;;\n");
    }
    let _ = writeln!(
        s,
        "        help)\n            [[ $(_writ_position '') == 1 ]] && _writ_words '{}'\n            ;;",
        names.join(" ")
    );
    s.push_str("    esac\n}\n\ncomplete -F _writ writ\n");
    s
}

// ---------------------------------------------------------------------------
// zsh

fn zq(s: &str) -> String {
    s.replace('\'', "'\\''")
        .replace('[', "\\[")
        .replace(']', "\\]")
}

fn zsh_action(v: Value) -> String {
    match v {
        Value::NewDir | Value::Identity | Value::Id => "_files -/".to_owned(),
        Value::File | Value::OutFile | Value::Subject => "_files".to_owned(),
        Value::Text => " ".to_owned(),
        Value::Choice(words) => format!("({})", words.join(" ")),
    }
}

fn zsh_opt(o: &Opt) -> String {
    let help = zq(o.help);
    let value = match o.value {
        Some((meta, v)) => format!(":{}:{}", zq(&meta.to_lowercase()), zsh_action(v)),
        None => String::new(),
    };
    let star = if o.many { "*" } else { "" };
    match (o.short, o.value.is_some()) {
        (Some(c), takes) => {
            let (s_suffix, l_suffix) = if takes { ("+", "=") } else { ("", "") };
            let excl = if o.many {
                String::new()
            } else {
                format!("(-{c} --{})", o.long)
            };
            format!(
                "'{star}{excl}'{{-{c}{s_suffix},--{}{l_suffix}}}'[{help}]{value}'",
                o.long
            )
        }
        (None, takes) => {
            let suffix = if takes { "=" } else { "" };
            format!("'{star}--{}{suffix}[{help}]{value}'", o.long)
        }
    }
}

fn zsh() -> String {
    let mut s = String::from(
        "#compdef writ\n\
         # zsh completion for writ(1). Generated by `writ completions zsh`.\n\
         # Install it as _writ in a directory on $fpath, or load it with\n\
         # source <(writ completions zsh) after compinit.\n\n\
         _writ_commands() {\n  local -a commands=(\n",
    );
    for spec in commands() {
        let _ = writeln!(
            s,
            "    '{}:{}'",
            spec.name,
            zq(spec.about).replace(':', "\\:")
        );
    }
    s.push_str(
        "    'help:print help for a command'\n  )\n  _describe -t commands 'writ command' commands\n}\n\n",
    );
    s.push_str(
        "_writ() {\n  local curcontext=$curcontext state state_descr line ret=1\n  typeset -A opt_args\n\n  _arguments -C \\\n",
    );
    for o in GLOBAL_OPTS {
        let _ = writeln!(s, "    {} \\", zsh_opt(o));
    }
    s.push_str(
        "    '(- :)'{-h,--help}'[print help]' \\\n    '(- :)'{-V,--version}'[print the version]' \\\n    ': :_writ_commands' \\\n    '*:: :->command' && ret=0\n\n",
    );
    s.push_str(
        "  if [[ $state == command ]]; then\n    curcontext=${curcontext%:*:*}:writ-$words[1]:\n    case $words[1] in\n",
    );
    for spec in commands() {
        let _ = writeln!(s, "      ({})\n        _arguments -s -S \\", spec.name);
        for o in spec.opts {
            let _ = writeln!(s, "          {} \\", zsh_opt(o));
        }
        s.push_str("          '(- *)'{-h,--help}'[print help]'");
        for (i, a) in spec.args.iter().enumerate() {
            let pos = if a.many {
                "*".to_owned()
            } else if a.optional {
                format!("{}:", i + 1)
            } else {
                (i + 1).to_string()
            };
            let _ = write!(
                s,
                " \\\n          '{pos}:{}:{}'",
                zq(&a.name.to_lowercase()),
                zsh_action(a.value)
            );
        }
        s.push_str(" && ret=0\n        ;;\n");
    }
    s.push_str("      (help)\n        _arguments ': :_writ_commands' && ret=0\n        ;;\n");
    s.push_str("    esac\n  fi\n  return ret\n}\n\n");
    s.push_str(
        r#"if [[ $funcstack[1] == _writ ]]; then
  # Autoloaded from $fpath: this file is the completion function.
  _writ "$@"
elif (( $+functions[compdef] )); then
  # Sourced or eval'd: register the function.
  compdef _writ writ
else
  print -u2 "writ: load compinit before writ's completions (autoload -Uz compinit && compinit)"
fi
"#,
    );
    s
}

// ---------------------------------------------------------------------------
// fish

fn fq(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"))
}

fn fish_action(v: Value) -> &'static str {
    match v {
        Value::NewDir | Value::Identity | Value::Id => {
            "-x -a '(__fish_complete_directories (commandline -ct))'"
        }
        Value::File | Value::OutFile | Value::Subject => "-r -F",
        Value::Text => "-x",
        Value::Choice(_) => "-x",
    }
}

fn fish_opt(cond: &str, o: &Opt) -> String {
    let mut s = format!("complete -c writ -n {cond}");
    if let Some(c) = o.short {
        let _ = write!(s, " -s {c}");
    }
    let _ = write!(s, " -l {}", o.long);
    let mut choices = None;
    if let Some((_, v)) = o.value {
        let _ = write!(s, " {}", fish_action(v));
        if let Value::Choice(words) = v {
            choices = Some(words);
        }
    }
    let _ = write!(s, " -d {}", fq(o.help));
    // The values get their own line, so each isn't shown with the option's
    // description.
    if let Some(words) = choices {
        let _ = write!(
            s,
            "\ncomplete -c writ -n {cond} -l {} -x -a {}",
            o.long,
            fq(&words.join(" "))
        );
    }
    s
}

const FISH_ARG_FN: &str = r#"# Succeeds if the cursor is at argument N (or "N+": N or later) of the
# writ command, counting arguments after the command name and skipping the
# values of the options listed after N.
function __writ_arg
    set -l want $argv[1]
    set -l takes $argv[2..-1]
    set -l n 1
    set -l skip 0
    set -l seen 0
    for t in (commandline -opc)[2..-1]
        if test $skip -eq 1
            set skip 0
            continue
        end
        if test $seen -eq 0
            switch $t
                case --color
                    set skip 1
                case '-*'
                case '*'
                    set seen 1
            end
            continue
        end
        switch $t
            case -
                set n (math $n + 1)
            case '--*=*'
            case '-*'
                contains -- $t $takes; and set skip 1
            case '*'
                set n (math $n + 1)
        end
    end
    if string match -q -- '*+' $want
        test $n -ge (string trim -r -c + -- $want)
    else
        test $n -eq $want
    end
end"#;

fn fish() -> String {
    let names: Vec<&str> = commands().iter().map(|c| c.name).chain(["help"]).collect();
    let mut s = format!(
        "# fish completion for writ(1). Generated by `writ completions fish`.\n\
         # Install it as ~/.config/fish/completions/writ.fish.\n\n\
         set -l commands {}\n\n\
         complete -c writ -f\n\n{}\n",
        names.join(" "),
        FISH_ARG_FN
    );
    let top = "\"not __fish_seen_subcommand_from $commands\"";
    for o in GLOBAL_OPTS {
        let _ = writeln!(s, "{}", fish_opt(top, o));
    }
    let _ = writeln!(
        s,
        "complete -c writ -n {top} -s h -l help -d 'print help'\n\
         complete -c writ -n {top} -s V -l version -d 'print the version'"
    );
    for spec in commands() {
        let _ = writeln!(
            s,
            "complete -c writ -n {top} -a {} -d {}",
            spec.name,
            fq(spec.about)
        );
    }
    let _ = writeln!(
        s,
        "complete -c writ -n {top} -a help -d 'print help for a command'"
    );
    for spec in commands() {
        let cond = format!("\"__fish_seen_subcommand_from {}\"", spec.name);
        let _ = writeln!(s, "\n# writ {}", spec.name);
        for o in spec.opts {
            let _ = writeln!(s, "{}", fish_opt(&cond, o));
        }
        let _ = writeln!(s, "complete -c writ -n {cond} -s h -l help -d 'print help'");
        // Arguments by position: __writ_arg counts the arguments before the
        // cursor, skipping the values of options that take one.
        let takes: Vec<String> = spec
            .opts
            .iter()
            .filter(|o| o.value.is_some())
            .flat_map(opt_names)
            .collect();
        for (i, a) in spec.args.iter().enumerate() {
            let at = if a.many {
                format!("{}+", i + 1)
            } else {
                (i + 1).to_string()
            };
            let action = match a.value {
                Value::File | Value::OutFile | Value::Subject => "-F".to_owned(),
                Value::NewDir | Value::Identity | Value::Id => {
                    "-a '(__fish_complete_directories (commandline -ct))'".to_owned()
                }
                Value::Choice(words) => format!("-a {}", fq(&words.join(" "))),
                Value::Text => continue,
            };
            let _ = writeln!(
                s,
                "complete -c writ -n \"__fish_seen_subcommand_from {}; and __writ_arg {at}{}{}\" {action}",
                spec.name,
                if takes.is_empty() { "" } else { " " },
                takes.join(" ")
            );
        }
    }
    let _ = writeln!(
        s,
        "\n# writ help\ncomplete -c writ -n \"__fish_seen_subcommand_from help\" -a {}",
        fq(&names.join(" "))
    );
    s
}
